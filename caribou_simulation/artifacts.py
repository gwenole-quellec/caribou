"""CARIBOU — Generate report artifacts in isolated processes without global plotting state."""

from io import BytesIO
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from tempfile import TemporaryDirectory
from zipfile import ZIP_DEFLATED, ZipFile


# ==================================================================================================
# Constants
# ==================================================================================================

ARTIFACTS = {
    "Mission preservation": "fig_missions",
    "Restrictions": "fig_restrictions",
    "Governance": "fig_governance",
    "Trade-off": "fig_tradeoff",
    "Outcome table": "table_outcomes",
}


# ==================================================================================================
# Utility function
# ==================================================================================================

def read_reports(uploads):
    """Read JSON reports or a result ZIP without extracting uploaded paths."""
    reports = {}
    for name, raw in uploads:
        if name.lower().endswith(".zip"):
            with ZipFile(BytesIO(raw)) as archive:
                entries = [
                    (Path(info.filename).name, archive.read(info))
                    for info in archive.infolist()
                    if not info.is_dir()
                    and Path(info.filename).name.startswith("budget_allocation_")
                    and info.filename.endswith(".json")
                ]
        else:
            entries = [(Path(name).name, raw)]
        for filename, content in entries:
            if not re.fullmatch(r"budget_allocation_\d+(?:p\d+)?pct\.json", filename):
                raise ValueError(f"Unrecognized simulation report filename: {filename}")
            report = json.loads(content)
            if report.get("schema_version") != "1.0" or not report.get("draws"):
                raise ValueError(
                    "Artifact generation requires CARIBOU reports with per-rule results. Rerun with Include per-rule results enabled."
                )
            if filename in reports:
                raise ValueError(f"Duplicate report: {filename}")
            reports[filename] = content
    if not reports:
        raise ValueError("No simulation reports were found.")
    return reports


# ==================================================================================================
# Artifact generation
# ==================================================================================================

def generate_artifacts(reports, selected, pooling=0.5, decimals=1, progress=None):
    """Return generated bytes, per-artifact errors and a downloadable archive."""
    if not selected or any(label not in ARTIFACTS for label in selected):
        raise ValueError("Select at least one artifact.")
    if not 0 <= pooling <= 1 or not 0 <= decimals <= 4:
        raise ValueError("Invalid table settings.")
    reports = read_reports(list(reports.items()))
    files, errors = {}, {}
    root = Path(__file__).resolve().parents[1]
    with TemporaryDirectory(prefix="caribou-artifacts-") as temporary:
        directory = Path(temporary)
        results = directory / "results"
        output = directory / "artifacts"
        results.mkdir()
        output.mkdir()
        for name, content in reports.items():
            (results / name).write_bytes(content)
        environment = dict(os.environ)
        environment["PYTHONPATH"] = (
            str(root) + os.pathsep + environment.get("PYTHONPATH", "")
        )
        environment["MPLBACKEND"] = "Agg"
        environment["MPLCONFIGDIR"] = str(directory / "matplotlib")
        if progress:
            progress(0, len(selected))
        for index, label in enumerate(selected, start=1):
            module = ARTIFACTS[label]
            command = [
                sys.executable,
                "-m",
                "caribou_simulation." + module,
                "--results-dir",
                str(results),
                "--output-dir",
                str(output),
            ]
            if module == "table_outcomes":
                command += ["--lambda", str(pooling), "--decimals", str(decimals)]
            try:
                result = subprocess.run(
                    command,
                    cwd=directory,
                    env=environment,
                    capture_output=True,
                    text=True,
                    timeout=180,
                )
                if result.returncode:
                    errors[label] = (result.stderr or result.stdout)[-2000:]
                else:
                    for path in output.glob(module + ".*"):
                        files[path.name] = path.read_bytes()
            except subprocess.TimeoutExpired:
                errors[label] = "Artifact generation exceeded 180 seconds."
            if progress:
                progress(index, len(selected))
    archive_bytes = BytesIO()
    with ZipFile(archive_bytes, "w", ZIP_DEFLATED) as archive:
        for name, content in files.items():
            archive.writestr(name, content)
        archive.writestr(
            "generation.json",
            json.dumps(
                {
                    "selected": selected,
                    "pooling": pooling,
                    "decimals": decimals,
                    "errors": errors,
                },
                indent=2,
            ),
        )
    return files, errors, archive_bytes.getvalue()
